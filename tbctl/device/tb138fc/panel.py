from __future__ import annotations

import re
import sys
from pathlib import Path

from tbctl.core import host
from tbctl.core.config import load
from tbctl.device.tb138fc import DATA
from tbctl.core.process import BuildError, log, run

PANEL_DIR = DATA / "kernel" / "panel"
TEMPLATE = PANEL_DIR / "panel-raydium-rm692h0.c.in"
INIT_SEQUENCE = PANEL_DIR / "rm692h0-init.inc"
DRIVER = PANEL_DIR / "panel-raydium-rm692h0.c"

LMDPDG_URL = "https://github.com/msm8953-mainline/linux-mdss-dsi-panel-driver-generator"
LMDPDG_REV = "6eed29a2b0a10e07939801d6b965f790f7664ca0"
STOCK_BASE_DTB = "dtbs/base00.dtb"
STOCK_PANEL_OVERLAY = "dtbos/ovl04.dtb"
INIT_HEADER = ("/* Generated by lmdpdg --dumb-dcs from the stock qcom,mdss-dsi-on-command "
               "(tbctl panel init-sequence) */")

REQUIRED_TOOLS = ("git", "fdtoverlay")


def render_driver() -> int:
    seq = [l.strip() for l in INIT_SEQUENCE.read_text(encoding="utf-8").splitlines()
           if l.startswith("\t")]
    seq = ["\t" + l for l in seq if "0x35, 0x00" not in l]
    driver = TEMPLATE.read_text(encoding="utf-8").replace("@@SEQ@@", "\n".join(seq))
    DRIVER.write_text(driver, encoding="utf-8", newline="\n")
    return len(seq)


def patch_lmdpdg(panel_py: Path) -> None:
    s = panel_py.read_text()
    if "dsi-default-panel" in s:
        return
    old = "\t\t\t\tpanel_phandles.add(fdt.getprop(display, 'qcom,dsi-panel').as_uint32())\n\t\t\telse:"
    new = ("\t\t\t\tph = fdt.getprop_or_none(display, 'qcom,dsi-panel') or "
           "fdt.getprop_or_none(display, 'qcom,dsi-default-panel')\n"
           "\t\t\t\tif ph is not None:\n"
           "\t\t\t\t\tpanel_phandles.add(ph.as_uint32())\n"
           "\t\t\telse:")
    if old not in s:
        raise BuildError(f"lmdpdg layout changed; update patch_lmdpdg ({panel_py})")
    panel_py.write_text(s.replace(old, new))


def fetch_lmdpdg(dest: Path) -> None:
    if not (dest / ".git").exists():
        dest.mkdir(parents=True, exist_ok=True)
        run(["git", "-C", str(dest), "init", "-q"])
        run(["git", "-C", str(dest), "remote", "add", "origin", LMDPDG_URL])
    run(["git", "-C", str(dest), "fetch", "-q", "--depth", "1", "origin", LMDPDG_REV])
    run(["git", "-C", str(dest), "checkout", "-q", "--force", LMDPDG_REV])
    patch_lmdpdg(dest / "panel.py")


def extract_on_sequence(generated_c: str) -> list[str]:
    on = re.search(r"\nstatic int \w+_on\(.*?\n}\n", generated_c, flags=re.S)
    if not on:
        raise BuildError("no *_on() function in the lmdpdg output")
    calls = re.findall(r"^\tdsi_dcs_write_seq\(dsi, (.*)\);$", on.group(0), flags=re.M)
    return [f"\tmipi_dsi_dcs_write_seq_multi(&dsi_ctx, {args});" for args in calls]


def init_sequence() -> int:
    cfg = load()
    host.ensure(host.require_tools(list(REQUIRED_TOOLS)))
    stock = cfg.work / "stock"
    base, overlay = stock / STOCK_BASE_DTB, stock / STOCK_PANEL_OVERLAY
    if not (base.is_file() and overlay.is_file()):
        raise BuildError(f"stock DTBs missing under {stock} (run `tbctl firmware stock-dt`)")
    lmdpdg = cfg.work / "lmdpdg"
    fetch_lmdpdg(lmdpdg)
    merged = stock / "merged-mtp.dtb"
    run(["fdtoverlay", "-i", str(base), "-o", str(merged), str(overlay)])
    gen = cfg.work / "panel-gen"
    run(["rm", "-rf", str(gen)])
    gen.mkdir(parents=True)
    run([sys.executable, str(lmdpdg / "lmdpdg.py"), "--dumb-dcs", str(merged)], cwd=gen,
        capture_output=True)
    outputs = [p for p in gen.glob("*/panel-*.c") if not p.name.startswith("panel-simple-")]
    if len(outputs) != 1:
        raise BuildError(f"expected one panel driver from lmdpdg, got {outputs}")
    seq = extract_on_sequence(outputs[0].read_text())
    INIT_SEQUENCE.write_text("\n".join([INIT_HEADER, *seq]) + "\n", encoding="utf-8",
                             newline="\n")
    log(f"{INIT_SEQUENCE}: {len(seq)} commands from {outputs[0].name}")
    return len(seq)
