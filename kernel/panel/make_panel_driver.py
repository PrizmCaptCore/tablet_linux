"""Fill panel-raydium-rm692h0.c.in with the init sequence in rm692h0-init.inc
(generated by tools/gen-panel.sh) and write panel-raydium-rm692h0.c."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
seq = open(os.path.join(HERE, "rm692h0-init.inc"), encoding="utf-8").read().splitlines()
# drop the generator comment line and the trailing "35 00" (tear-on is sent explicitly)
seq = ["\t" + l.strip() for l in seq if l.startswith("\t") and "0x35, 0x00" not in l]
tpl = open(os.path.join(HERE, "panel-raydium-rm692h0.c.in"), encoding="utf-8").read()
out = tpl.replace("@@SEQ@@", "\n".join(seq))
open(os.path.join(HERE, "panel-raydium-rm692h0.c"), "w", encoding="utf-8", newline="\n").write(out)
print(f"panel-raydium-rm692h0.c: {len(seq)} init commands")
